#ifndef BSP_WS2812_H
#define BSP_WS2812_H

// ============================================================================
// 文件：bsp_ws2812.h
// 功能：WS2812（兼容 WS2812B）单总线智能彩灯驱动的对外接口声明。
// 原理：WS2812 是把红/绿/蓝三色亮度数据用一根数据线串接起来的灯珠。
//       驱动时不直接翻转 GPIO，而是用定时器 TIM3 的 PWM 输出，把每个数据位
//       表示成不同占空比的方波：逻辑 1 的高电平较长、逻辑 0 的高电平较短；
//       再由 DMA 把整串波形自动搬进定时器比较寄存器连续发出，全程不占用 CPU。
//       发送结束后保持约 50us 低电平，灯珠即锁定颜色并刷新显示。
// 说明：本文件只声明接口，具体实现见 bsp_ws2812.c。
// ============================================================================

#include "main.h"
#include "tim.h"
 
// 定时器 PWM 比较值：数值越大，一个 PWM 周期内高电平时间越长（占空比越大）。
#define WS_H           66   // 逻辑“1”码对应的比较计数值（高电平约占 2/3 周期）
#define WS_L           33   // 逻辑“0”码对应的比较计数值（高电平约占 1/3 周期）
// 复位信号对应的脉冲数量：发送完一帧颜色后，需要持续低电平让灯珠复位
#define WS_REST        45   // 复位信号脉冲数量
#define LED_1_NUM      1  // 直灯板WS2812灯个数
// 每颗灯珠数据占用的缓冲槽数：一颗灯珠 24bit（G/R/B 各 8bit），故占 24 个元素
#define DATA_LEN       24   // WS2812数据长度，单个需要24个字节
// 发送完颜色后需保持 50us 以上低电平（约 40 个 PWM 周期）让灯珠复位刷新；
// 这里取 50 个周期（留有余量），即发送缓冲末尾额外填充的空闲周期数
#define WS2812_RST_NUM 55   // 官方复位时间为50us（40个周期），保险起见使用50个周期

// 初始化 WS2812 驱动：清空发送缓冲，并把 0 号灯珠熄灭。
extern void WS2812_Init(void);
// 设置第 num 颗灯珠的颜色。
// 参数 num：灯珠序号（从 0 开始，当前只支持 0 号）；
// 参数 R/G/B：红/绿/蓝亮度，取值 0~255，0 最暗、255 最亮。
extern void WS2812_Set(uint16_t num,uint8_t R,uint8_t G,uint8_t B);

#endif
