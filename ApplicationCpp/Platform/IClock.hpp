#ifndef robot_clock_hpp
#define robot_clock_hpp

// ============================================================================
// i_clock.hpp —— 平台无关的单调时钟（monotonic clock）抽象接口
// ----------------------------------------------------------------------------
// 作用：向框架/业务层提供一个“只往前走、永不回退”的计时源，用来测量时间间隔
//       （例如控制周期长度、某个节点的执行耗时）。框架代码只依赖本接口，
//       不关心底层究竟是用 STM32 的 DWT 计数器，还是将来跑在 NUC/Linux 上时
//       用 clock_gettime()。
//
// 设计要点：
//   - 这是一个纯虚类（抽象接口）：只规定“能做什么”，不规定“怎么做”。
//   - 依赖倒置：高层代码依赖抽象“接口”，底层硬件提供“实现”，两者解耦。
//       将来把工程从 STM32 移植到 NUC（Linux）时，只要再写一个 i_clock 的
//       实现类（换成 Linux 的时钟系统调用）即可，所有调用方代码无需改动。
//   - 多态：调用方保存的是 i_clock* 指针，真正读时钟时由运行时动态分派到
//       实际实现（如 STM32 的 DwtClock），因此同一套上层代码可适配不同平台。
//
// 术语：
//   - 单调时钟：读数随时间只增不减、不受“系统时间被修改”影响的时钟，
//       因此非常适合测量“时间间隔”（用两次读数相减），而不适合报“日期”。
//   - 微秒（us）：1us = 1/1,000,000 秒。本接口统一以微秒为时间单位。
// ============================================================================

#include <cstdint>

namespace robot::platform {

// 平台无关的单调时钟接口；STM32 使用 DWT（内核周期计数器）实现，
// 未来 Linux 可替换为 clock_gettime(CLOCK_MONOTONIC) 之类的后端。
class i_clock {
public:
    // 虚析构：保证通过基类指针 i_clock* 删除派生对象时，
    // 派生类自己的析构函数能被正确调用（否则会只析构基类部分，造成资源泄漏）。
    virtual ~i_clock() = default;
    // 读取当前时间：返回“自时钟启动以来”累计的微秒数（单调递增）。
    // 参数：无。
    // 返回：uint64_t 时间戳，单位微秒（us）。用 64 位是防止在较高频率下很快溢出；
    //       调用两次相减即可得到一段代码执行了多久。
    // const：表示“读时钟”不会修改对象自身状态，允许对 const 对象调用。
    // = 0：纯虚函数，本身没有实现，必须由派生类提供具体实现。
    virtual uint64_t now_us() const = 0;
};

} // namespace robot::platform

#endif /* robot_clock_hpp */
