// ============================================================================
// Beep.h —— 蜂鸣器(无源蜂鸣器 PWM 驱动)模块头文件
// ----------------------------------------------------------------------------
// 模块用途：
//   用定时器 TIM12 通道 2 输出 PWM 方波，驱动哨兵机器人上的无源蜂鸣器发声。
//   改变方波周期即可改变音高，改变方波持续时间即可改变音符时值，占空比固定 50%。
//   典型流程：Beep_Init() 初始化 -> Beep_PlayNotes() 把音符入队 -> 蜂鸣器任务逐个播放。
// 相关术语：
//   无源蜂鸣器：内部没有振荡电路，必须由外部送入方波才发声；输入方波频率不同，
//              发出的音高就不同(对比：有源蜂鸣器通电即响，无法变调)。
//   周期(period)：一个完整方波所占的时间，单位微秒(us)；周期越小频率越高、音越高。
//   占空比：一个周期内高电平所占比例，50% 即高低电平各占一半(方波音色最响)。
//   八度：相邻八度的频率成 2 倍关系(如中音 Do≈523Hz，高音 Do≈1046Hz)。
// ============================================================================
#ifndef _BEEP_H_
#define _BEEP_H_

#include "main.h"

// 音高表(枚举)：低/中/高三个八度各音(Do~Si)对应的方波周期，单位微秒(us)。
// 周期 = 1 / 频率；例如 T_M1=1911us 约合 523Hz，即中音 Do。
enum
{
	//不响：周期 0 表示不发声(静音/休止符)
	T_None=0,
	//低八度：低音区，频率约 262~487Hz
  T_L1=3822, //低音 Do
  T_L2=3405, //低音 Re
  T_L3=3034, //低音 Mi
  T_L4=2863, //低音 Fa
  T_L5=2551, //低音 Sol
  T_L6=2272, //低音 La
  T_L7=2052, //低音 Si
	//中八度：中音区，频率约 523~988Hz
  T_M1=1911, //中音 Do
  T_M2=1703, //中音 Re
  T_M3=1517, //中音 Mi
  T_M4=1432, //中音 Fa
  T_M5=1276, //中音 Sol
  T_M6=1136, //中音 La
  T_M7=1012, //中音 Si
	//高八度：高音区，频率约 1046~1976Hz
  T_H1=956, //高音 Do
  T_H2=851, //高音 Re
  T_H3=758, //高音 Mi
  T_H4=716, //高音 Fa
  T_H5=638, //高音 Sol
  T_H6=568, //高音 La
  T_H7=506  //高音 Si
};

// 音符时值表：不同长度的音符对应的持续时间，单位毫秒(ms)。
// 基准为 4/4 拍、速度(BPM)=100：每分钟 100 拍，故一拍(四分音符)=60/100 秒=600ms。
enum
{
	D_Whole=2400,//全音符：4 拍 = 2400ms
	D_Half=1200,//二分音符：2 拍 = 1200ms
	D_Quarter=600,//四分音符：1 拍 = 600ms
	D_Eighth=300,//八分音符：半拍 = 300ms
	D_Sixteenth=150//十六分音符：1/4 拍 = 150ms
};

// 一个音符的数据结构：描述“发什么音、响多久”
typedef struct
{
	uint16_t period;//发声周期，单位 us(取值见上方 T_x 枚举；0 表示静音)
	uint16_t duration;//持续时长，单位 ms(取值见上方 D_x 枚举)
}Note;

// 蜂鸣器初始化：启动 TIM12 通道 2 的 PWM，并初始化音符队列。上电后调用一次即可。
// 参数：无
// 返回值：无
void Beep_Init(void);
// 播放单个音符(非阻塞)：把 1 个音符放入队列，并通知蜂鸣器任务去播放。
// 参数：note —— 指向要播放的音符(函数会把其内容拷贝进队列，无需常驻)
// 返回值：无
void Beep_PlayOneNote(Note *note);
// 播放一串音符(非阻塞)：依次把多个音符放入队列，并通知蜂鸣器任务去播放。
// 参数：notes —— 音符数组首地址；noteNum —— 音符个数(不应超过队列容量 MAX_NOTE_QUEUE_SIZE)
// 返回值：无
void Beep_PlayNotes(Note notes[],uint8_t noteNum);
// 阻塞式播放队列中全部音符：函数会一直等到全部播完才返回。
// 参数：无
// 返回值：无
// 警告：内部使用软件忙等延时，会阻塞 CPU，不应在任务调度正常运行期间调用。
void Beep_Block_PlayAll(void);
// 蜂鸣器任务回调：由蜂鸣器任务周期调用，取一个音符播放并等待其时值；无音符时挂起等待通知。
// 参数：无
// 返回值：无
void Task_Beep_Callback(void);

// 头文件结束
#endif
