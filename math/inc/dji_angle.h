/*
 * 文件：dji_angle.h
 * 说明：大疆（DJI）电机机械角度的模运算工具，用于把编码器角度展开到“最短路径”。
 *
 * 术语：
 *   - 大疆电机：RoboMaster 常用的大疆（DJI）电机（如 GM6020、M2006 等），其转子
 *     位置由磁编码器测量。
 *   - 编码器计数：一圈（机械 360°）被均分为 8192 个计数，读数范围 0 ~ 8191，
 *     相邻一个计数约等于 360/8192 ≈ 0.0439°。
 *   - 回绕（wrap）：读数到 8191 后再前进就跳回 0；反之从 0 后退会跳到 8191。
 *     因此直接对两个读数做减法会出现 ±8192 的假跳变，需要按模 8192 展开到离目标
 *     最近的那一圈，才能得到真实的最小角度差。
 *
 * 本文件仅声明一个函数：把编码器角度展开到与目标最接近的等价角。
 */

/* 包含守卫宏 _DJI_ANGLE_H：保证本头文件在同一个编译单元中只被展开一次 */
#ifndef _DJI_ANGLE_H
#define _DJI_ANGLE_H

/* 使用 int32_t 需引入 stdint.h（定宽有符号 32 位整型） */
#include <stdint.h>

/* 函数：ModularDJIAngleTowards
 * 用途：对大疆编码器角度做“模 8192”展开，返回与 target 最接近、且与原角度机械
 *       等价（二者相差 8192 的整数倍，机械指向相同）的角度值。
 *       典型用途：跨圈时就近取角 / 求最短路径，避免 ±8192 的跳变。
 * 参数：
 *   degree —— 待展开的大疆编码器角度（单位：编码器计数，0 ~ 8191 表示一圈；
 *             头文件中此形参名为 degree，定义处名为 dji_angle，含义完全相同）
 *   target —— 参考目标角度（同一编码器计数制），返回值会向它靠拢
 * 返回值：展开后的整型角度（编码器计数制），满足 result ≡ degree (mod 8192)，
 *         且 |result - target| ≤ 4096（即结果落在目标的半圈以内）。
 */
int32_t ModularDJIAngleTowards(int32_t degree, int32_t target);

/* 结束包含守卫 _DJI_ANGLE_H */
#endif
