#ifndef _DEGREE_H
#define _DEGREE_H

/*
 * 文件：degree.h
 * 作用：角度模运算。把任意角度"折叠"到以某个目标角度为中心的 360 度等价区间内。
 * 术语：
 *   - 角度模运算：两个角度只要相差 360 度的整数倍，就表示同一个朝向
 *     （例如 -30 度、330 度、690 度其实是同一个朝向）。
 *   - 最短路径：从当前角度转到目标角度时，选择转过角度绝对值最小的方向（不超过 180 度）。
 *   - 角度标准化：把角度限制到某个固定区间（例如本函数的 [target-180, target+180]）。
 * 说明：本文件只声明一个角度处理函数，用于把当前角度换算成与目标角度最接近的等价角度，
 *       方便计算"最短转向路径"。
 */

/*
 * 用途：将当前角度 degree 折算成"以 target 为中心、跨度 360 度"区间内的等价角度。
 *       返回一个与 degree 相差 360 度整数倍、且落在 [target-180, target+180] 内的角度。
 * 参数：
 *   - degree：当前角度（单位：度，可为任意实数，不限制范围）。
 *   - target：参考的目标角度（单位：度，可为任意实数）。
 * 返回：与 degree 等价（相差 360 度的整数倍）且最接近 target 的角度（单位：度），
 *       取值范围 [target-180, target+180]。
 *       该返回值与 target 的差即为从 degree 转到 target 的最短旋转角。
 */
float ModularDegreeTowards(float degree, float target);

#endif
